// 事例データの型定義
export interface Case {
  id: string;
  title: string;
  industry: string;
  region: string;
  prefecture?: string;
  city?: string;
  companySize: 'small' | 'medium' | 'large'; // small: ~50名, medium: 50-300名, large: 300名~
  challenge: string;
  proposal: string;
  result: string;
  tags: string[];
  createdAt: Date;
  updatedAt: Date;
}

// 振り返りデータの型定義（検索対象外の内部データ）
export interface Reflection {
  id: string;
  industry: string;
  region: string;
  companySize: 'small' | 'medium' | 'large';
  situation: string; // 商談の状況
  failurePoint: string; // 失敗したポイント
  customerReaction: string; // 顧客の反応
  reflectionNotes: string; // 振り返り内容
  improvementActions: string[]; // 改善アクション
  relatedSuccessCases?: string[]; // 関連する成功事例のID
  createdAt: Date;
}

// 検索フィルターの型定義
export interface SearchFilters {
  query?: string;
  industry?: string;
  region?: string;
  prefecture?: string;
  city?: string;
  companySize?: 'small' | 'medium' | 'large';
  tags?: string[];
  dateFrom?: Date;
  dateTo?: Date;
  favorites?: boolean; // お気に入りのみ表示
}

// 検索結果の型定義
export interface SearchResult {
  case: Case;
  relevanceScore: number;
  matchedFields: string[];
  highlights?: {
    title?: string;
    challenge?: string;
    proposal?: string;
    result?: string;
  };
}

